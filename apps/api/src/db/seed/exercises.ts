const PRESET_CREATED_AT = new Date('2026-10-24T00:00:00Z')

/**
 * Idempotent upsert of presets, run on every boot. Rows are only rewritten when a
 * field actually changed, so unchanged presets keep their serverVersion and
 * clients don't re-pull them on every deploy.
 */
export async function seedPresetExercises(db: Db): Promise<void> {
  const now = new Date()
  await db
    .insert(exercises)
    .values(
      PRESET_EXERCISES.map((p) => ({
        ...p,
        userId: null,
        isPreset: true,
        createdAt: PRESET_CREATED_AT,
        updatedAt: now,
      })),
    )
    .onConflictDoUpdate({
      target: exercises.id,
      set: {
        name: sql`excluded."name"`,
        type: sql`excluded."type"`,
        muscleGroup: sql`excluded."muscleGroup"`,
        equipment: sql`excluded."equipment"`,
        defaultRestSeconds: sql`excluded."defaultRestSeconds"`,
        deletedAt: null,
        updatedAt: sql`excluded."updatedAt"`,
      },
      setWhere: sql`(${exercises.name}, ${exercises.type}, ${exercises.muscleGroup}, ${exercises.equipment}, ${exercises.defaultRestSeconds}, ${exercises.deletedAt})
        IS DISTINCT FROM (excluded."name", excluded."type", excluded."muscleGroup", excluded."equipment", excluded."defaultRestSeconds", NULL)`,
    })
}
